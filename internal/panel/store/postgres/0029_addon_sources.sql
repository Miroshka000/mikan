-- Third-party addon sources (internal/panel/addons, sources.go): a URL the admin added, whose
-- entries show in the marketplace as unofficial. key is the ed25519 public key (base64) the
-- source signed with when it was added, '' for an unsigned source; a later fetch with another
-- key, or none, is refused. error is the code of the last fetch that failed, '' when it held.
CREATE TABLE addon_sources (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url        TEXT   NOT NULL UNIQUE,
  key        TEXT   NOT NULL DEFAULT '',
  title      TEXT   NOT NULL,
  added_by   BIGINT REFERENCES admins(id) ON DELETE SET NULL,
  added_at   BIGINT NOT NULL,
  fetched_at BIGINT NOT NULL DEFAULT 0,
  error      TEXT   NOT NULL DEFAULT ''
);
CREATE INDEX addon_sources_added_by ON addon_sources (added_by);

-- Which source an installed addon came from. RESTRICT: a source with an addon installed from
-- it cannot be deleted under it.
CREATE TABLE addon_origins (
  addon_id  TEXT   PRIMARY KEY,
  source_id BIGINT NOT NULL REFERENCES addon_sources(id) ON DELETE RESTRICT
);
CREATE INDEX addon_origins_source ON addon_origins (source_id);

