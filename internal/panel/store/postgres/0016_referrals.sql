-- +goose Up
-- The referral programme of the Telegram bot. An account has one referral code and
-- invites others by it; a Telegram account is bound to at most one referrer, forever, so
-- one invitee cannot be counted twice. What a referrer earns is an internal balance in
-- kopecks (never in Telegram Stars, whatever the invitee paid with) and days added to
-- their subscription.
CREATE TABLE referral_accounts (
  tg_id      BIGINT PRIMARY KEY,
  code       TEXT NOT NULL UNIQUE,
  balance    BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE referrals (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_tg_id BIGINT NOT NULL REFERENCES referral_accounts(tg_id) ON DELETE CASCADE,
  -- One referrer for good: an invitee cannot be re-bound to somebody else later.
  referee_tg_id BIGINT NOT NULL UNIQUE,
  code          TEXT NOT NULL,
  created_at    BIGINT NOT NULL,
  first_paid_at BIGINT
);
CREATE INDEX referrals_referrer ON referrals(referrer_tg_id, id DESC);

-- What a referrer earned from one applied payment: kopecks into the balance (percent) or
-- days onto the subscription (threshold). payment_id is unique, so one payment pays out
-- once; the referrer is counted once per rule for it (every_n).
CREATE TABLE referral_rewards (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_tg_id BIGINT NOT NULL REFERENCES referral_accounts(tg_id) ON DELETE CASCADE,
  referral_id   BIGINT NOT NULL REFERENCES referrals(id) ON DELETE CASCADE,
  payment_id    BIGINT UNIQUE REFERENCES payments(id) ON DELETE SET NULL,
  rule_id       TEXT NOT NULL DEFAULT '',
  kind          TEXT NOT NULL CHECK (kind IN ('percent','days')),
  amount        BIGINT NOT NULL DEFAULT 0 CHECK (amount >= 0),
  days          BIGINT NOT NULL DEFAULT 0 CHECK (days >= 0),
  every_n       BIGINT NOT NULL DEFAULT 1 CHECK (every_n >= 1),
  currency      TEXT NOT NULL DEFAULT 'RUB',
  created_at    BIGINT NOT NULL,
  reverted_at   BIGINT
);
CREATE INDEX referral_rewards_referrer ON referral_rewards(referrer_tg_id, id DESC);
CREATE INDEX referral_rewards_payment ON referral_rewards(payment_id);

-- What the balance paid for an invoice, in kopecks. One invoice spends once; a refund
-- gives it back.
CREATE TABLE referral_spends (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id BIGINT UNIQUE REFERENCES payments(id) ON DELETE CASCADE,
  tg_id      BIGINT NOT NULL,
  amount     BIGINT NOT NULL CHECK (amount > 0),
  created_at BIGINT NOT NULL,
  reverted_at BIGINT
);
CREATE INDEX referral_spends_tg ON referral_spends(tg_id, id DESC);

-- How many qualifying payments a referrer has under each rule, so a "every N" rule pays
-- out on the Nth, the 2Nth and so on.
CREATE TABLE referral_counters (
  tg_id   BIGINT NOT NULL REFERENCES referral_accounts(tg_id) ON DELETE CASCADE,
  rule_id TEXT NOT NULL,
  paid    BIGINT NOT NULL DEFAULT 0 CHECK (paid >= 0),
  PRIMARY KEY (tg_id, rule_id)
);

