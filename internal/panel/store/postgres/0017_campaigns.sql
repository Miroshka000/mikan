-- +goose Up
-- Ad campaign tags of the Telegram bot: an admin gives each ad its own deep link
-- (t.me/<bot>?start=camp_<tag>) and the panel counts, per campaign, how many people
-- arrived, how many bought for the first time and how many renewed.
--
-- The tag is a public, human-chosen label, not a secret: anybody may follow a link with
-- any tag, so nothing here is trusted for access — it only says where a chat came from.
-- A chat belongs to the campaign of the first tagged link it opened and never moves
-- (campaign_visits.chat_id is unique), the same way a referral is bound once.
CREATE TABLE campaign_tags (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tag        TEXT NOT NULL UNIQUE,
  name       TEXT NOT NULL DEFAULT '',
  note       TEXT NOT NULL DEFAULT '',
  enabled    INTEGER NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  deleted    INTEGER NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

-- One row per chat that followed a tagged link. The unique chat_id makes a second tagged
-- link — another campaign's, or the same one's — change nothing: arrival is counted once.
CREATE TABLE campaign_visits (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaign_tags(id) ON DELETE CASCADE,
  -- Not a foreign key: a chat may open a link a moment before it writes its own tg_chats
  -- row, and a chat that never subscribes must still be counted as an arrival.
  chat_id     BIGINT NOT NULL UNIQUE,
  tag         TEXT NOT NULL,
  first_seen  BIGINT NOT NULL
);
CREATE INDEX campaign_visits_campaign ON campaign_visits(campaign_id, id DESC);

-- What a tagged chat's payments did, told apart as "bought" (the first subscription) and
-- "renewed" (any tariff payment after the first). payment_id is unique, so one payment is
-- counted once; a refund of it takes the count back rather than leaving a false sale.
CREATE TABLE campaign_events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaign_tags(id) ON DELETE CASCADE,
  chat_id     BIGINT NOT NULL,
  payment_id  BIGINT UNIQUE REFERENCES payments(id) ON DELETE SET NULL,
  kind        TEXT NOT NULL CHECK (kind IN ('bought', 'renewed')),
  amount      BIGINT NOT NULL DEFAULT 0 CHECK (amount >= 0),
  currency    TEXT NOT NULL DEFAULT 'RUB',
  created_at  BIGINT NOT NULL,
  reverted_at BIGINT
);
CREATE INDEX campaign_events_campaign ON campaign_events(campaign_id, id DESC);
CREATE INDEX campaign_events_payment ON campaign_events(payment_id);

