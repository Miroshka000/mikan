-- +goose Up
-- What came over from a sales bot (Bedolaga). The accounts whose balance was carried, once
-- each, so a second run adds nothing; and their payment history, kept apart from mikan's own
-- payments: those were taken by the bot, are not refunded here and are not mikan's revenue.
CREATE TABLE imported_accounts (
  source TEXT NOT NULL,
  tg_id  BIGINT NOT NULL,
  amount BIGINT NOT NULL, -- what was carried, in minor units of the balance's currency
  at     BIGINT NOT NULL,
  PRIMARY KEY (source, tg_id)
);
CREATE TABLE imported_payments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source      TEXT NOT NULL,
  external_id TEXT NOT NULL,          -- the bot's id of the transaction
  tg_id       BIGINT NOT NULL,
  kind        TEXT NOT NULL CHECK (kind ~ '^[a-z_]{1,32}$'), -- the bot's type: deposit, subscription_payment, …
  amount      BIGINT NOT NULL,        -- minor units of currency, as the bot had it
  currency    TEXT NOT NULL CHECK (currency ~ '^[A-Z]{3,4}$'),
  method      TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  created_at  BIGINT NOT NULL,
  UNIQUE (source, external_id)
);
CREATE INDEX imported_payments_tg ON imported_payments (tg_id, created_at DESC);

-- +goose Down
DROP TABLE imported_payments;
DROP TABLE imported_accounts;
