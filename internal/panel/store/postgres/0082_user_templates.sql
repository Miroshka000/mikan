-- Templates of clients (#295): what a client made by one gets, for the admin who hands
-- access out in batches rather than selling it in the bot. A template names a tariff and
-- what goes over it; a NULL is the tariff's own, and a limit or a term of 0 is none
-- (unlimited, never ends). The folder and the group let their templates go when they are
-- deleted, as they let their clients go: the template then puts its clients in no folder,
-- and in their tariff's group. Tariffs are archived, not deleted: a template of an archived
-- tariff makes no clients until the admin picks another. Tags are JSON in TEXT, as users
-- keep theirs; name_pattern names the clients of a batch ({n}: their number).
CREATE TABLE user_templates (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              TEXT    NOT NULL UNIQUE,
  tariff_id         BIGINT  NOT NULL REFERENCES tariffs(id) ON DELETE CASCADE,
  traffic_limit     BIGINT  CHECK (traffic_limit >= 0),
  device_limit      BIGINT  CHECK (device_limit BETWEEN 0 AND 100),
  speed_limit       BIGINT  CHECK (speed_limit BETWEEN 0 AND 100000),
  term_days         BIGINT  CHECK (term_days BETWEEN 0 AND 3650),
  starts_on_connect BOOLEAN,
  folder_id         BIGINT  REFERENCES user_folders(id) ON DELETE SET NULL,
  group_id          BIGINT  REFERENCES user_groups(id) ON DELETE SET NULL,
  tags              TEXT    NOT NULL DEFAULT '[]',
  note              TEXT    NOT NULL DEFAULT '',
  name_pattern      TEXT    NOT NULL DEFAULT '',
  created_at        BIGINT  NOT NULL,
  updated_at        BIGINT  NOT NULL
);

