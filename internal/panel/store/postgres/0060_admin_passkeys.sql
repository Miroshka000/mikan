-- +goose Up
-- The passkeys an admin signs in with beside the password (WebAuthn, api/passkeys.go).
-- credential_id is the id the authenticator gave the key: a sign-in names the key by it, and
-- two admins never share one. credential is the record go-webauthn keeps of the key (its
-- public key, flags and signature counter) as JSON; it is replaced after each sign-in, as the
-- counter moves. name is the admin's label for it.
CREATE TABLE admin_passkeys (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id      BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  credential_id BYTEA  NOT NULL UNIQUE,
  name          TEXT   NOT NULL,
  credential    TEXT   NOT NULL,
  created_at    BIGINT NOT NULL,
  last_used_at  BIGINT
);
CREATE INDEX admin_passkeys_admin ON admin_passkeys (admin_id);

-- +goose Down
DROP TABLE admin_passkeys;
