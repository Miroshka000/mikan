-- +goose Up
-- The places clients reach an inbound at (#01): an address, a port, the TLS name, the HTTP
-- Host and the uTLS fingerprint, each empty (port 0) for what clients get without it. The
-- host at position 0 is the inbound's default one, the template's mikan.client, which
-- migration 64 copies in and the panel keeps equal to it (domain.syncDefaultHost) while
-- subscriptions still read the template; the others follow it in the order of position.
CREATE TABLE inbound_hosts (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inbound_id  BIGINT NOT NULL REFERENCES inbounds(id) ON DELETE CASCADE,
  position    BIGINT NOT NULL CHECK (position >= 0),
  address     TEXT   NOT NULL DEFAULT '',
  port        BIGINT NOT NULL DEFAULT 0 CHECK (port BETWEEN 0 AND 65535),
  sni         TEXT   NOT NULL DEFAULT '',
  host        TEXT   NOT NULL DEFAULT '',
  fingerprint TEXT   NOT NULL DEFAULT '',
  -- Deferrable, so that hosts change places in one UPDATE; checked at the end of each
  -- statement unless a transaction defers it.
  UNIQUE (inbound_id, position) DEFERRABLE INITIALLY IMMEDIATE
);
-- One default host per inbound, the conflict target of its upsert: ON CONFLICT takes no
-- deferrable constraint.
CREATE UNIQUE INDEX inbound_hosts_default ON inbound_hosts (inbound_id) WHERE position = 0;

