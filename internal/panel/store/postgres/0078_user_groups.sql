-- +goose Up
-- Groups of clients (#290): what a group sees and how its subscriptions look. A client is in
-- one group at most: its own (user_group_members), or else the one of its tariff
-- (user_group_tariffs), so a tariff's buyers and its trial go to the tariff's group without
-- anyone moving them. A group that is deleted lets its clients and tariffs go, as a folder
-- does. Neither link is a column of users or tariffs: their rows are what the bot addon reads,
-- held to golden files (internal/panel/model).
--
-- Access: a group leaves the servers to the tariff (chosen_servers 0), or gives its own (1):
-- nodes whole, with the protocols added to them later, and single protocols, chosen as a tariff
-- chooses them. A client whose card lists protocols of its own keeps them over both.
CREATE TABLE user_groups (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           TEXT NOT NULL UNIQUE,
  color          TEXT NOT NULL DEFAULT 'gray', -- a name from the palette the API knows
  emoji          TEXT NOT NULL DEFAULT '',
  sort           BIGINT NOT NULL DEFAULT 0,
  chosen_servers BIGINT NOT NULL DEFAULT 0 CHECK (chosen_servers IN (0, 1)),
  created_at     BIGINT NOT NULL
);

CREATE TABLE user_group_nodes (
  group_id BIGINT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE,
  node_id  BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, node_id)
);
CREATE INDEX user_group_nodes_node ON user_group_nodes (node_id);

CREATE TABLE user_group_inbounds (
  group_id   BIGINT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE,
  inbound_id BIGINT NOT NULL REFERENCES inbounds(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, inbound_id)
);
CREATE INDEX user_group_inbounds_inbound ON user_group_inbounds (inbound_id);

-- The group a client is in by its own card.
CREATE TABLE user_group_members (
  user_id  BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  group_id BIGINT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE
);
CREATE INDEX user_group_members_group ON user_group_members (group_id);

-- The group of a tariff's clients that have none of their own.
CREATE TABLE user_group_tariffs (
  tariff_id BIGINT PRIMARY KEY REFERENCES tariffs(id) ON DELETE CASCADE,
  group_id  BIGINT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE
);
CREATE INDEX user_group_tariffs_group ON user_group_tariffs (group_id);

-- Who an address for clients is shown to by group (#275): group_mode only: to the clients of
-- these groups alone; never: to every client but theirs; '': to every one (groups empty). The
-- ids have no foreign key: a deleted group is taken out of them in its own transaction, and
-- an address left "only" for no group is shown to nobody until the admin picks again.
ALTER TABLE inbound_hosts
  ADD COLUMN group_mode TEXT     NOT NULL DEFAULT '' CHECK (group_mode IN ('', 'only', 'never')),
  ADD COLUMN groups     BIGINT[] NOT NULL DEFAULT '{}' CHECK (cardinality(groups) <= 100);

-- +goose Down
