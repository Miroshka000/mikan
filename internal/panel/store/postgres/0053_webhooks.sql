-- Outgoing webhooks (internal/panel/webhooks): the admin names an address and the events it is
-- told of, and the panel POSTs each one there, signed. An endpoint follows the feed of events
-- (addon_events) with a cursor of its own: last_id is the last event it took, moved only after
-- a 2xx, so what was not taken is sent again and nothing is skipped. A new endpoint starts at
-- the end of the feed and is told what happens from then on.
-- secret signs every delivery (HMAC-SHA256) and is shown to the admin once; the signature needs
-- the value itself, so it is kept as it is, like the payment keys of an addon. events are the
-- types it is told of, none meaning all of them. allow_local lets it reach this server's own
-- addresses and the LAN's, which the panel refuses to dial otherwise.
CREATE TABLE webhook_endpoints (
  id          BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        TEXT    NOT NULL,
  url         TEXT    NOT NULL,
  secret      TEXT    NOT NULL,
  events      TEXT[]  NOT NULL DEFAULT '{}',
  enabled     BOOLEAN NOT NULL DEFAULT true,
  allow_local BOOLEAN NOT NULL DEFAULT false,
  last_id     BIGINT  NOT NULL DEFAULT 0,
  created_at  BIGINT  NOT NULL,
  updated_at  BIGINT  NOT NULL
);

-- What was sent to an endpoint: a row per event, made by its first attempt and updated by each
-- one after, so attempts, the answer's status and the failure are those of the last. A test
-- event is not in the feed (event_id NULL) and is tried once. status: retrying, while the
-- event is still to be sent again; delivered, after a 2xx; failed, when it will not be tried
-- again (a test that did not go through, an event that left the feed or the endpoint's choice).
-- error is a code of the webhooks package, "" after a 2xx; response_code is the answer's HTTP
-- status, 0 when there was none. Rows are dropped a week after their last attempt.
CREATE TABLE webhook_deliveries (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint_id   BIGINT NOT NULL REFERENCES webhook_endpoints(id) ON DELETE CASCADE,
  event_id      BIGINT,
  type          TEXT   NOT NULL,
  status        TEXT   NOT NULL CHECK (status IN ('retrying', 'delivered', 'failed')),
  attempts      BIGINT NOT NULL,
  response_code BIGINT NOT NULL DEFAULT 0,
  error         TEXT   NOT NULL DEFAULT '',
  created_at    BIGINT NOT NULL,
  updated_at    BIGINT NOT NULL,
  UNIQUE (endpoint_id, event_id)
);
CREATE INDEX webhook_deliveries_endpoint ON webhook_deliveries (endpoint_id, id DESC);
CREATE INDEX webhook_deliveries_updated ON webhook_deliveries (updated_at);
CREATE INDEX webhook_deliveries_retrying ON webhook_deliveries (id) WHERE status = 'retrying';

