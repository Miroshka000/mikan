-- +goose Up
-- The subscription templates (internal/sub/<core>): the admin's own profiles of a core, the
-- core's config without the servers, which the panel puts the user's servers into. A
-- response rule may name one; a core's default is what its apps get otherwise, and with
-- none they get the built-in profile.
CREATE TABLE sub_templates (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  core       TEXT NOT NULL CHECK (core IN ('mihomo', 'singbox', 'xray')),
  name       TEXT NOT NULL,
  body       TEXT NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT false,
  created_at BIGINT NOT NULL, -- unix seconds
  updated_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX sub_templates_default ON sub_templates (core) WHERE is_default;

-- The own Clash profile of the settings (sub_template, a JSON string) is the default mihomo
-- template now, and the setting is gone. The row is taken first, so that no other setting's
-- value is read as JSON.
WITH own AS MATERIALIZED (SELECT value::jsonb AS v FROM settings WHERE key = 'sub_template')
INSERT INTO sub_templates (core, name, body, is_default, created_at, updated_at)
SELECT 'mihomo', 'Clash', v #>> '{}', true, EXTRACT(EPOCH FROM now())::BIGINT, EXTRACT(EPOCH FROM now())::BIGINT
FROM own WHERE jsonb_typeof(v) = 'string' AND btrim(v #>> '{}', E' \t\r\n') <> '';
DELETE FROM settings WHERE key = 'sub_template';

-- +goose Down
-- The default mihomo template goes back to the setting; the others have no place there.
INSERT INTO settings (key, value)
SELECT 'sub_template', to_jsonb(body)::text FROM sub_templates WHERE core = 'mihomo' AND is_default
ON CONFLICT (key) DO UPDATE SET value = excluded.value;
DROP TABLE sub_templates;
