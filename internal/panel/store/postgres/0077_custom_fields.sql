-- Fields of the admin's own on users and nodes (an order number, a phone, the hoster's
-- account): the admin names them, the cards show and edit them, the list's search finds
-- them. They only describe: nothing the user may do or the node carries depends on them.
CREATE TABLE custom_fields (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope      TEXT   NOT NULL CHECK (scope IN ('user', 'node')),
  -- key is the name in the API, label the name on screen; kind says how a value reads.
  key        TEXT   NOT NULL CHECK (key ~ '^[a-z][a-z0-9_]{0,31}$'),
  label      TEXT   NOT NULL CHECK (char_length(label) BETWEEN 1 AND 64),
  kind       TEXT   NOT NULL CHECK (kind IN ('text', 'number', 'bool', 'date', 'url')),
  sort       BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  UNIQUE (scope, key)
);

-- A value is text in the field's kind (number: a decimal, bool: true, date: YYYY-MM-DD);
-- no row: no value.
CREATE TABLE user_field_values (
  user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  field_id BIGINT NOT NULL REFERENCES custom_fields(id) ON DELETE CASCADE,
  value    TEXT   NOT NULL CHECK (char_length(value) BETWEEN 1 AND 500),
  PRIMARY KEY (user_id, field_id)
);
CREATE INDEX user_field_values_field ON user_field_values (field_id);

CREATE TABLE node_field_values (
  node_id  BIGINT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
  field_id BIGINT NOT NULL REFERENCES custom_fields(id) ON DELETE CASCADE,
  value    TEXT   NOT NULL CHECK (char_length(value) BETWEEN 1 AND 500),
  PRIMARY KEY (node_id, field_id)
);
CREATE INDEX node_field_values_field ON node_field_values (field_id);

