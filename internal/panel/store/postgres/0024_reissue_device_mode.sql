-- +goose Up
-- The subscriber's own new links (domain.ReissueRules): the admin limits how many a period,
-- and a restart must not give the count back, as the limit exists against a leaked link
-- being reissued over and over. Like device_unbinds, one row for each.
CREATE TABLE link_reissues (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  at      BIGINT NOT NULL
);
CREATE INDEX link_reissues_user_at ON link_reissues (user_id, at);

-- How a device limit counts (domain.DeviceMode): 'bound', the devices bound to the
-- subscription by their ids (today's rule), or 'online', any number of devices may bind
-- and only the ones online at once count, which the nodes enforce by the device's address.
-- A user takes the tariff's mode with its other limits.
ALTER TABLE tariffs ADD COLUMN device_mode TEXT NOT NULL DEFAULT 'bound' CHECK (device_mode IN ('bound', 'online'));
ALTER TABLE users ADD COLUMN device_mode TEXT NOT NULL DEFAULT 'bound' CHECK (device_mode IN ('bound', 'online'));

-- +goose Down
ALTER TABLE users DROP COLUMN device_mode;
ALTER TABLE tariffs DROP COLUMN device_mode;
DROP TABLE link_reissues;
