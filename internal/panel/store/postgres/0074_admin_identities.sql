-- +goose Up
-- The accounts an admin signs in with beside the password (#20): a GitHub account or a
-- Telegram one, linked from the admin's own session. subject is the account's id there
-- (never its name, which its owner can change); name is that name, for the admin's list.
CREATE TABLE admin_identities (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id     BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  provider     TEXT NOT NULL CHECK (provider IN ('github', 'telegram')),
  subject      TEXT NOT NULL CHECK (char_length(subject) BETWEEN 1 AND 64),
  name         TEXT NOT NULL DEFAULT '' CHECK (char_length(name) <= 128),
  created_at   BIGINT NOT NULL,
  last_used_at BIGINT,
  -- One account opens one admin, and an admin has one account of each provider.
  UNIQUE (provider, subject),
  UNIQUE (admin_id, provider)
);

-- +goose Down
DROP TABLE admin_identities;
