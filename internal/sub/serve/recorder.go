package serve

import (
	"bytes"
	"net/http"
)

// recorder keeps an answer in memory for a Preview: its status, headers and body. It cannot
// be taken over, so a rule that drops the connection only marks the exchange (refuse).
type recorder struct {
	header http.Header
	status int
	body   bytes.Buffer
}

func newRecorder() *recorder { return &recorder{header: http.Header{}} }

func (r *recorder) Header() http.Header { return r.header }

func (r *recorder) WriteHeader(status int) {
	if r.status == 0 {
		r.status = status
	}
}

func (r *recorder) Write(p []byte) (int, error) {
	if r.status == 0 {
		r.status = http.StatusOK
	}
	return r.body.Write(p)
}
